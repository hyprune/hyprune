#!/usr/bin/env python3
"""Original Hyprune CC0 quiet room. Deterministic, no external assets or bake."""
import json
from pathlib import Path
import struct

root = Path(__file__).resolve().parents[1] / 'worlds/minimal'
root.mkdir(parents=True, exist_ok=True)
positions = []


def quad(a, b, c, d):
    positions.extend([a, b, c, a, c, d])


quad((-6, 0, -8), (-6, 0, 6), (6, 0, 6), (6, 0, -8))
quad((-6, 0, -8), (6, 0, -8), (6, 5, -8), (-6, 5, -8))
quad((-6, 0, 6), (-6, 0, -8), (-6, 5, -8), (-6, 5, 6))
quad((6, 0, -8), (6, 0, 6), (6, 5, 6), (6, 5, -8))
quad((6, 0, 6), (-6, 0, 6), (-6, 5, 6), (6, 5, 6))
# A desk and a spare lectern with simple warm material, below tool planes.
quad((-3.8, .85, -2.6), (-3.8, .85, -1.4), (-.6, .85, -1.4), (-.6, .85, -2.6))
blob = b''.join(struct.pack('<fff', *p) for p in positions)
gltf = {'asset': {'version': '2.0', 'generator': 'Hyprune original quiet room'},
        'scene': 0, 'scenes': [{'nodes': [0]}], 'nodes': [{'mesh': 0}],
        'meshes': [{'primitives': [{'attributes': {'POSITION': 0}, 'material': 0}]}],
        'materials': [{'doubleSided': True, 'pbrMetallicRoughness': {
            'baseColorFactor': [.24, .34, .36, 1], 'metallicFactor': 0, 'roughnessFactor': .85}}],
        'buffers': [{'uri': 'geometry.bin', 'byteLength': len(blob)}],
        'bufferViews': [{'buffer': 0, 'byteOffset': 0, 'byteLength': len(blob)}],
        'accessors': [{'bufferView': 0, 'componentType': 5126, 'count': len(positions), 'type': 'VEC3',
                       'min': [min(p[i] for p in positions) for i in range(3)],
                       'max': [max(p[i] for p in positions) for i in range(3)]}]}


def anchor(id, position, size, kind, role):
    return dict(id=id, pose=dict(position=position, rotation=[0, 0, 0, 1]), size=size,
                screenType='com.hyprune.window',
                mount=dict(type=kind, role=role, interaction='focus-in' if role == 'mounted-workspace' else 'in-place'))


world = dict(formatVersion='0.3', id='com.hyprune.minimal', version='0.1.0', name='Quiet Desk',
             license='CC0-1.0', scene='scene.gltf', defaultSpawn='arrival',
             spawns=[dict(id='arrival', pose=dict(position=[0, 0, 4], rotation=[0, 0, 0, 1]))],
             collision=[dict(node=0, shape='mesh', layer='static')],
             anchors=[anchor('quiet-desk-wall', [0, 2.7, -7.9], [7, 3.94], 'facade-wall', 'mounted-workspace'),
                      anchor('quiet-desk-operator-desk', [-2.2, 1.85, -2], [3.2, 1.8], 'operator-desk', 'tool-mount'),
                      anchor('quiet-desk-lectern', [2.8, 1.7, -2], [2.4, 1.35], 'lectern', 'tool-mount')],
             areas=[dict(id='quiet-desk', workspaceSlot='01', primaryAnchor='quiet-desk-wall',
                         toolAnchors=['quiet-desk-operator-desk', 'quiet-desk-lectern'], dataAnchors=[],
                         theme='Quiet Desk', spawnId='arrival')],
             attribution=[dict(path='.', author='Hyprune contributors', license='CC0-1.0',
                               source='https://github.com/hyprune/hyprune')])
(root / 'geometry.bin').write_bytes(blob)
for name, data in [('scene.gltf', gltf), ('world.json', world)]:
    (root / name).write_text(json.dumps(data, indent=2) + '\n')
(root / 'ATTRIBUTION.md').write_text('Original geometry by Hyprune contributors, CC0-1.0.\n'
                                    'Generated by scripts/generate-minimal.py in hyprune/hyprune.\n'
                                    'No textures, external assets, or Blender dependency.\n')
(root / 'LICENSE').write_text('Original assets dedicated under CC0 1.0.\nhttps://creativecommons.org/publicdomain/zero/1.0/\n')
